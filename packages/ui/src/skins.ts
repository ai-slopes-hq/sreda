/** Sets every token of the skin as `--<token>` on `root` (the document element by default). */
export function applySkin(name: SkinName, root: HTMLElement = document.documentElement): void {
  const skin = SKINS[name];
  for (const t of TOKENS) root.style.setProperty(`--${t}`, skin[t]);
}
